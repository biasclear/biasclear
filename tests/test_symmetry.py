def test_red_team_pairs_are_all_kept():
    round_2 = sum(len(pairs) for pairs in RED_TEAM_ROUND_2.values())
    round_3 = sum(len(pairs) for pairs in RED_TEAM_ROUND_3.values())
    round_4 = sum(len(pairs) for pairs in RED_TEAM_ROUND_4.values())
    round_5 = sum(len(pairs) for pairs in RED_TEAM_ROUND_5.values())
    site_review = sum(len(pairs) for pairs in RED_TEAM_SITE_REVIEW.values())
    name_free = sum(len(pairs) for pairs in NAME_FREE_RULES.values())
    # The red team's pairs found in each round (the site review found five),
    # plus pairs written with the fixes: each one runs, is a known limit or is
    # retired.
    assert len(RED_TEAM) + len(KNOWN_LIMITS) + len(RETIRED_PAIRS) >= 220 + 301 + 243 + 183 + 350 + 5
    # 297 of the second round's pairs passed; rules 2.0.0a3 retired six and
    # rules 2.0.0a4 one.
    assert round_2 >= 297 - 7
    # 240 of the third round's pairs passed; rules 2.0.0a3 retired nine.
    assert round_3 >= 240 - 9
    # 179 of the red team's 183 pairs (two became known limits in the fifth
    # round), and five more written with the fix for names after a source
    # noun.
    assert round_4 >= 184
    # 336 of the red team's 350 pairs, and nine more written with the fixes;
    # rules 2.0.0a3 retired twelve (three of them had passed), and rules
    # 2.0.0a4 one more.
    assert round_5 >= 345 - 13
    # The site review's five pairs (its faith-name pair passes since rules
    # 2.0.0a3), and five more written with the fix.
    assert site_review >= 10
    assert name_free >= 35
    # The fix round's pairs: every counterexample the red team gave, plus the
    # two lowercase-name limits of rules 2.0.0a3, which now pass; one pair
    # ("pigs") is a known limit.
    assert sum(len(pairs) for pairs in FIX_ROUND_1.values()) >= 135
    # Every known limit and retired pair has a reason, and no pair is both.
    assert {why for _, _, why in KNOWN_LIMITS} == set(_LIMIT_REASONS)
    assert {why for _, _, why in RETIRED_PAIRS} == set(_RETIRED_REASONS)
    limits = {(a, b) for a, b, _ in KNOWN_LIMITS}
    retired = {(a, b) for a, b, _ in RETIRED_PAIRS}
    running = {tuple(p.values) for p in RED_TEAM}
    assert len(limits) == len(KNOWN_LIMITS) and len(retired) == len(RETIRED_PAIRS)
    assert not limits & retired and not limits & running and not retired & running
    # Where a retired pair has a true mirror, the mirror runs.
    assert len(NAME_FREE_RULES["mirrors of retired pairs"]) >= 20


