def _bare(name: str) -> str:
    return name[4:] if name.lower().startswith("the ") else name


def _fill(template: str, name: str) -> str:
    return template.format(X=name[:1].upper() + name[1:], x=name, b=_bare(name))


def _pairs() -> list:
    out = []
    for group, pairs in ENTITY_PAIRS.items():
        templates = TEMPLATES + (ORG_TEMPLATES if group in ORG_GROUPS else [])
        for a, b in pairs:
            for i, t in enumerate(templates):
                out.append(pytest.param(_fill(t, a), _fill(t, b), id=f"{group}|{a}|{b}|t{i}"))
    for i, (a, b) in enumerate(LABEL_PAIRS):
        out.append(pytest.param(a, b, id=f"labels|{i}"))
    return out


