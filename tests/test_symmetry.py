"""Swapped-pair symmetry suite (ticket E3). A required check in CI.

Each pair is one name or label, swapped into the same sentence. Both sides
must raise exactly the same rules. Every template must raise at least one
rule, so no check is vacuous, and together the templates raise every rule in
the pack. Many templates put the swapped name inside a rule's window (between
"because of" and "everything", in "the controversial ... plan", in the
first words of a lead, and so on), so a name's length or wording is tested
where it could matter. The red team's pairs (``RED_TEAM_PAIRS``) are
checked the same way, but may raise nothing on both sides when the swap sits
in a citation. Their second to fifth rounds are ``RED_TEAM_ROUND_2``,
``RED_TEAM_ROUND_3``, ``RED_TEAM_ROUND_4`` and ``RED_TEAM_ROUND_5``; their
review of the website is ``RED_TEAM_SITE_REVIEW``; and their first fix round on
the public seed (rules 2.0.0a4) is ``FIX_ROUND_1``.

Names here are test inputs, not rule content: rules never name anyone. The
people, parties, organizations, faith bodies, outlets, schools, awards and
programs are made up, each with the shape of the name it replaced (length,
particles, initials, punctuation, and the rule words a name holds);
countries, places, peoples and faiths are named as they are, and so are
generic government bodies and seats of government ("the Census Bureau",
"the Kremlin").

Known limits:

- Windows are bounded, and counted in words, not characters. A name slot
  and a gap between two parts of a rule each hold up to 16 name tokens (32
  for "either ... or"; eight modifiers between "leading", "top" or "key" and
  the group noun, where a connector inside a name counts with the word
  before it: "Center for Ostrevan Progress scholars"). A name token may hold
  periods, "!", colons, curly apostrophes and en dashes ("Jr.'s",
  "RallyOn.org", "St\u00f3:l\u014d", "O\u2019Callan"), may be a parenthesized
  word ("Berwick (Minn.)", "Maumee (Ohio)'s"), and may end in a comma that
  does not start a clause ("Parents, Families and Allies of Lesbians and
  Gays"). Every name below fits; a longer name can still stop a match.
- ``MEDIA_BURIED_QUALIFIER`` keeps v1's character windows: the qualifier must
  come after 200 characters, and within 150 characters of "however". Its
  point is where the qualifier sits in the text, so a longer name earlier in
  the text can move it. The pairs below use names of up to eight words there.
- Sentence ends are read the same way for every name: a period followed by
  a space ends the sentence ("Voters blamed Trask." like "Voters blamed
  Hartig."), except before a lowercase word ("gov. nesbit") or after a title
  or other closed-class abbreviation or a one-letter initial ("Sen. Harlan",
  "Wall St.", "Gordon W. Lusk") when the next word is not one that starts
  sentences ("The", "He", "But"). So "Wall St. Critics were furious" still
  reads as one sentence. An abbreviation at the end of a hyphenated word is
  not a title: the party-state tags "D-Calif." and "R-N.Y." end a sentence
  like "R-Ohio." does.
- Citations: a citation counts when any part of it is within 120 characters
  of the claim, so a long name inside it ("(Center on Revenue and Policy
  Priorities, 2021)") is seen like a short one. A name inside a citation may
  hold "/", "+", "*", "@", "#", "%", "!", curly quotes, dashes, a bracketed
  or parenthesized acronym and numbers, and sources may be joined by ";". It
  may be written in any script and start with any letter ("(\u00c9ric
  Vaudour 2019)", "(\u738b 2019)"). A scripture reference of every tradition
  counts ("(Qur'an 2:177)", "(Sanhedrin 37a)"), as "(1 Cor. 13:4)" did.
- Abbreviations that are not sentence ends are a closed class: titles of
  every tradition and language ("Rep." and "Dem.", "Fr." and "Bro.", "Sr."
  and "Sis.", "Bp." and "Eld.", "Rev." and "Ps.", "Abp." and "Metr.", "Sh.",
  "Ust.", "Rab.", "Ven.", "Dra.", "Profa.", "Smt.", "Shri.", "Hr.", "Sig."),
  ranks ("Lt.", "Wg.", "Sqn."), "St." and "Sts.", "Univ.", "Inst.", "Fdn.",
  the AP abbreviation of every state that has one ("Calif.", "Mass.", "Ga."),
  and school words ("Theol.", "Sem.", "Div."). A one-letter initial ("R."
  for a rabbi, "S." for a Sardar) continues a sentence too. No country's or
  nationality's abbreviation is on the list, so "Amer.", "Am." and "Brit."
  end a sentence alike; "Fr." and "Ind." are on it as a title and a state, so
  the same spellings used for a nationality do not (``KNOWN_LIMITS``,
  "abbreviation").
- A capitalized trigger word ("History", "Research") counts only at the
  start of a sentence, where it cannot be told apart from a name that is that
  one word ("Time has shown ..." for a magazine called Time). A capitalized
  fear word ("Invasion", "Existential Risk", "Right Side of History") does
  not count inside a capitalized name: right after a capitalized word or
  "of", "for", "on", "and", or right before a capitalized word. At the start
  of a sentence after "The", that also drops a real use ("The Invasion is
  here"). A capitalized insult counts after a capitalized word ("The Big
  Lie"), and not before one ("Talking Points Ledger", "Young Communists
  League"). A capitalized idiom, pronoun, evidence or
  intensifier word is part of a name ("As a Whole Larder employee", "Granite
  One", "with Varnell Review", "Key Circle members", "Leading Stage says").
  A word before a trigger is part of the same name only in the same
  sentence ("Vallorans. Most economists agree" like "conservatives. Most
  economists agree"), and a word that starts with a digit counts like a
  capitalized one ("The Project 2029 Catastrophe" like "The 1742 Project
  Catastrophe"). A capitalized adjective ("Catastrophic", "Devastating") is
  read by the word before it only: the word after it is the noun it
  modifies ("Catastrophic Black unemployment" like "Catastrophic white
  unemployment").
- A capitalized "All" or "Most" counts only at the start of a sentence;
  inside one it starts a name ("Leaders at All Saints say", "the All India
  Lokmitra Congress"). "the all ..." and "the most ..." are not
  quantifiers, and "Most" before a style of address is part of it ("Most
  Rev. Timothy Doran says" like "Rt. Rev. Marilyn Bekke says").
- A capitalized intensifier ("Leading", "Top", "Key") counts only right
  before its group noun ("Leading economists agree", "Prominent M\u0101ori
  agree"). With a modifier between them it cannot be told from a name that
  starts with the same word ("Key Circle members"), so it does not count,
  whatever the modifier's case ("Top Black economists" like "Top white
  economists"). A lowercase intensifier takes any modifier.
- A capitalized credential adjective followed only by name words up to the
  verb is part of a name ("Leading Stage says", "Respected Mayor Rudy Gilardi
  says"). Name words may be joined by short lowercase particles and
  connectors ("Bill de Vallon", "Ursula von der Heide", "the University of
  Kelsor at Wexley", "Ashgrove Theological Seminary in the City of New York"),
  and may start with a digit ("12 Weeks for Life", "450.org") or a lowercase
  prefix ("al-Saadi", "theKora").
- No rule holds a word that names, or is built from the name of, a person,
  party, movement, ideology, faith, country, program, outlet, institution or
  school (rules 2.0.0a3; ``tests/test_neutrality_lint.py``).
  ``DISSENT_DISMISSAL`` keeps dismissal words that can be aimed at anyone,
  which count anywhere ("cranks", "shills", "sheeple", "<any word> nuts"),
  each beside its mirror where it is aimed at one side; role and conduct
  words, which count only where the text applies them as a label ("they're
  just radicals", "he called them fanatics", "those bosses", "She is a
  radical."), while neutral stance and civic role words ("activists",
  "advocates", "partisans", "skeptics") are not labels on either side; and
  claim labels ("misinformation", "talking points"), which count at the end
  of a phrase, not inside a name ("the global disinformation registry") or
  as a sentence's topic ("She studies disinformation."). A group's own name
  counts only in an open frame that takes any word: "Only a ___ would say
  that", "Of course the ___ would say that", "That's just what the ___ want
  you to think", "Typical ___!" (one to three words or a capitalized name,
  whatever its ending, before an exclamation mark) and an order to disregard
  ("Ignore the ___."), whose object is one to three words that are not
  function words or common words for things ("the previous email"), or a
  capitalized name of up to 16 words, and ends the clause ("Ignore the noise
  from the fan." does not count). So "They're just socialists." and "They're just libertarians." are
  both unmarked, and "Only a socialist would say that." and "Only a
  libertarian would say that." both count. A pair that sets a group's name
  against a dismissal word ("They are fascists." / "They are fanatics.") is
  not a mirror (``RETIRED_PAIRS``); its mirrors ("They are fascists." /
  "They are communists.", "They are fanatics." / "They are cultists.") run.
  Where an insult aimed at one side counts, a common-word insult aimed at the
  other side counts too ("snowflakes" and "deplorables", "groomers" and "book
  banners"), never a word built from a name.
- Word lists are closed classes of common nouns, mirrored for both sides,
  with no faith-specific noun: "the clergy", "the congregations",
  "worshippers" and "houses of worship" count for every faith. Since rules
  2.0.0a4 ``CAUSAL_TOTALIZATION`` reads any plural noun phrase of one to
  three words that ends the clause, after a determiner or bare ("destroying
  the churches" like "destroying the mosques", "destroying evangelicals" like
  "destroying Catholics"), so no list decides whose people count, and its
  closed list of other objects holds each entry's mirror ("the free market"
  and "the welfare state", "progress" and "tradition"). The cost is that a
  literal loss of plural things reads the same way ("The frost destroyed the
  petals.").
- ``INSTITUTIONAL_POSITION_AS_SETTLED`` reads any subject before "has
  concluded that", capitalized or not ("the Fed", "the unions", "wren
  oakes"), at the cost of some false positives ("Researchers have found
  that ..."). An evidence word before the subject blocks it only when it
  heads its phrase ("after a review of the data,"), not when it modifies
  another noun ("after a hearth research council briefing").
- The red team's pairs that still differ are ``KNOWN_LIMITS`` below, each
  with its reason, run as strict expected failures. A known limit is a pair
  that swaps sides and keeps the kind of word: the same wording aimed at one
  side is marked and aimed at the other is not. A pair that changes the kind
  of word instead (a dismissal word against a group's own name, "experts"
  against "historians", "critics" against "Catholics", "history" against
  "God") is not a mirror: it is in ``RETIRED_PAIRS`` with a one-line reason,
  and is neither run nor counted as a limit.
"""

